"""Metadata generator - titles, descriptions, keywords, and category via the LLM gateway.

The prompt and the post-processing below encode Adobe's published metadata
rules, because a title or keyword that breaks one of them is a refusal reason
rather than a cosmetic problem:

* Title: **70 characters maximum**, plain text, **no commas or special
  characters**, natural language (not a keyword dump).
* Keywords: up to **49**, ordered by importance, because **the first 10 carry
  the greatest search weight**.
* Each keyword used once; a single language only; local spelling.
* No artist names, real people, brands, trademarks, fictional characters, or
  government agencies - and no entry from Adobe's known-restrictions list.

Sources (helpx, verified 2026-09):
* content-policies-guidelines/metadata/tips-effective-titles-keywords.html
* manage-your-portfolio/csv-requirements-content.html
* content-policies-guidelines/content-policies/known-restrictions.html
"""

import logging
from pathlib import Path

from config import settings
from services.adobe_categories import CATEGORY_CODES, resolve_category
from services.adobe_restrictions import scan_metadata
from services.asset_naming import normalise_name
from services.llm_client import LLMError, chat_json

logger = logging.getLogger(__name__)

FORBIDDEN_TAGS = {"ai", "generative", "stock", "midjourney", "illustration", "image", "nobody", "copyspace"}

#: Adobe prohibits these in generative AI titles and keywords; violations can
#: cost the account, so they are stripped after generation.
PROHIBITED_TERMS = (
    "midjourney",
    "dall-e",
    "dalle",
    "stable diffusion",
    "chatgpt",
    "generated by ai",
)

#: Adobe: "Title | 70 characters maximum". The generator is told a slightly
#: lower target so a trailing word is never chopped mid-phrase.
TITLE_TARGET = 68
#: Characters the model may use for the filename *stem*. Adobe's 30-character
#: filename cap includes the extension, so the stem gets the remainder; a little
#: headroom is kept back because the batch de-duplicator may need to append a
#: ``-2`` marker to a colliding name.
FILENAME_STEM_TARGET = 26
#: Adobe's ceiling; the prompt targets the same figure so nothing is wasted.
MAX_KEYWORDS = settings.CSV_MAX_KEYWORDS
#: Keywords in these positions influence search ranking most, so the prompt
#: requires the strongest terms there.
HIGH_IMPACT_SLOTS = settings.KEYWORDS_HIGH_IMPACT

_CATEGORY_LIST = ", ".join(
    f"{code}={name}" for code, name in CATEGORY_CODES.items()
)

METADATA_PROMPT = """Generate Adobe Stock optimized metadata for this image. Respond with ONLY valid JSON (no markdown fences):
{{
  "title": "<string, max {title_target} characters, natural English sentence, descriptive and commercially appealing>",
  "filename": "<string, a short descriptive filename stem in lower-case hyphenated words, no extension, max {filename_target} characters>",
  "description": "<string, one or two plain sentences describing the image content>",
  "keywords": ["<up to {max_keywords} keyword strings, ordered from most to least important>"],
  "category": "<the single best Adobe Stock category code, as a number>"
}}

Title rules:
- Maximum {title_target} characters. Shorter is better.
- A natural, readable phrase or short sentence - never a list of keywords.
- Plain text only: NO commas, semicolons, slashes, pipes, quotation marks, or other special characters.
- Describe the actual subject and setting. Do not include camera or gear terms, and do not include technical specifications.

Filename rules:
- Lower-case words separated by single hyphens. No spaces, dots, underscores, accents, or other punctuation.
- Maximum {filename_target} characters. Do not add a file extension - only the stem.
- Describe the specific subject of THIS image, so the file can be recognised in a folder of similar assets.
- Use the strongest searchable words, because the filename is what a customer sees in the download.
- Do NOT include any date, number, serial, or random code. No identifiers of any kind.

Keyword rules:
- Return up to {max_keywords} keywords, ordered by importance.
- The FIRST {high_impact} keywords carry the greatest search weight, so put the most relevant subject, action, and setting terms there.
- Use each keyword only once. No duplicates, singular and plural variants of the same word, or repeated concepts.
- Write in ONE language only (English). Use local spelling (color, not colour).
- Prefer the words a customer would actually type when searching.

Content rules:
- Do NOT include any of these forbidden terms: AI, generative, stock, midjourney, illustration, image, nobody, copyspace.
- Do NOT name any artist, real person, celebrity, fictional character, brand, trademark, logo, or government agency.
- Do NOT mention any landmark, monument, sports league, or organisation that could be protected by intellectual property.
- Do NOT imply the image depicts an actual newsworthy event.
- Choose the category from this exact list: {categories}"""


def _truncate_title(title: str, limit: int = TITLE_TARGET) -> str:
    """Clip a title to Adobe's limit on a word boundary."""
    if len(title) <= limit:
        return title
    clipped = title[:limit]
    last_space = clipped.rfind(" ")
    # Only break on a space when doing so keeps most of the available length;
    # otherwise a single long token would be lost entirely.
    if last_space > limit // 2:
        clipped = clipped[:last_space]
    return clipped.rstrip(" ,;:-")


def generate_metadata(file_path: str | Path, api_key: str | None = None) -> dict | None:
    """Generate title, description, keywords, and category for an approved image.

    Args:
        file_path: Path to the image file.
        api_key: Retained for call-site compatibility; the gateway key comes
            from settings.LLM_API_KEY (or the legacy GEMINI_API_KEY).

    Returns dict with title, description, keywords, category or None on failure.
    """
    if api_key:
        logger.debug("generate_metadata: explicit api_key ignored; using configured gateway key")

    prompt = METADATA_PROMPT.format(
        categories=_CATEGORY_LIST,
        title_target=TITLE_TARGET,
        filename_target=FILENAME_STEM_TARGET,
        max_keywords=MAX_KEYWORDS,
        high_impact=HIGH_IMPACT_SLOTS,
    )

    try:
        data = chat_json(file_path, prompt, temperature=0.2)
    except LLMError as exc:
        logger.error("Metadata generation failed for %s: %s", file_path, exc)
        return None

    title = str(data.get("title", "")).strip()
    description = str(data.get("description", "")).strip()
    keywords = data.get("keywords", [])

    if not isinstance(keywords, list):
        keywords = []
    keywords = [str(kw).strip() for kw in keywords if str(kw).strip()]

    # Post-processing: strip characters Adobe rejects in the Title field, then
    # clip to length. Both are hard portal-side rules, not preferences.
    from services.csv_export import sanitize_title

    title = sanitize_title(title)
    title = _truncate_title(title)

    # Post-processing: strip forbidden tags, prohibited tool names, and any
    # subject from Adobe's known-restrictions list. Deduplication happens here
    # too, because a model will happily emit "sky" twice.
    cleaned_keywords: list[str] = []
    seen: set[str] = set()
    blocked: list[str] = []
    for keyword in keywords:
        lowered = keyword.lower()
        if lowered in FORBIDDEN_TAGS:
            continue
        if any(term in lowered for term in PROHIBITED_TERMS):
            continue
        # A restricted brand or landmark in a keyword is an IP risk.
        if scan_metadata(keyword):
            blocked.append(keyword)
            continue
        if lowered in seen:
            continue
        seen.add(lowered)
        cleaned_keywords.append(keyword)

    if blocked:
        logger.info(
            "Dropped %d restricted keyword(s) for %s: %s",
            len(blocked),
            file_path,
            ", ".join(blocked[:5]),
        )

    # Cap at Adobe's keyword ceiling, keeping the most relevant first.
    cleaned_keywords = cleaned_keywords[:MAX_KEYWORDS]

    if not title:
        logger.warning("Generated metadata has empty title for %s", file_path)
        return None

    # The title itself can name a restricted subject; that is worth surfacing
    # rather than silently rewriting, because the image may genuinely depict it.
    title_risks = scan_metadata(title)

    # The model was asked to name the file as well as describe it. The name is
    # normalised through the same rules the operator's own renames go through
    # (slugified, JPEG extension, 30-character cap), so a proposal is always
    # directly applicable - never something the operator has to fix by hand.
    #
    # An absent or useless answer stays None rather than becoming the generic
    # "asset.jpg" that `normalise_name` falls back to: a placeholder offered as a
    # suggestion would be applied to a whole batch and destroy every name in it.
    raw_filename = str(data.get("filename", "") or "").strip()
    suggested_filename = normalise_name(raw_filename) if raw_filename else None

    return {
        "title": title,
        "description": description,
        "keywords": cleaned_keywords,
        "category": resolve_category(data.get("category")),
        "suggested_filename": suggested_filename,
        "title_restriction_warnings": title_risks,
        "blocked_keywords": blocked,
    }
